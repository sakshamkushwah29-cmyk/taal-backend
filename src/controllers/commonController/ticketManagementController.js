const getAllGeneratedByTicketId = catchAsync(async (req, res, next) => {
    let { eventId, sessionId, isVip, validForAllDays, page = 1, limit = 10, ticketStatus = "confirmed", search } = req.query;

    if (!eventId) return next(new AppError("eventId is required", 400));
    if (!isValidId(eventId)) return next(new AppError("Invalid event id", 400));
    if (sessionId && !isValidId(sessionId)) return next(new AppError("Invalid session id", 400));
    if (ticketStatus && !['pending', 'confirmed', 'failed'].includes(ticketStatus)) {
        return next(new AppError('Invalid status value', 400));
    }
    if (!search) search = ""

    const pageNum = parseInt(page);
    const pageSize = parseInt(limit);

    // -------- Build Root Match Object --------
    const matchBooking = {
        event: new mongoose.Types.ObjectId(eventId),
        ticketStatus,
        //search using attendee name inside root
        $or: [
            { "attendeeDetails.name": { $regex: search, $options: "i" } },

        ]
    };
    if (sessionId) matchBooking.eventSession = new mongoose.Types.ObjectId(sessionId);

    if (typeof isVip !== "undefined") matchBooking.isVipTicket = isVip === "true";
    if (typeof validForAllDays !== "undefined") matchBooking.validForAllDays = validForAllDays === "true";

    const orGeneratedBy = [
        { generatedBy: "admin" },
        { generatedBy: { $exists: false } }
    ];

    // -------- Aggregation Pipeline --------
    const pipeline = [
        { $match: { $and: [matchBooking, { $or: orGeneratedBy }] } },
        // Lookup Event
        {
            $lookup: {
                from: "events",
                localField: "event",
                foreignField: "_id",
                as: "event"
            }
        },
        { $unwind: { path: "$event", preserveNullAndEmptyArrays: true } },
        // Lookup Session
        {
            $lookup: {
                from: "eventsessions",
                localField: "eventSession",
                foreignField: "_id",
                as: "session"
            }
        },
        { $unwind: { path: "$session", preserveNullAndEmptyArrays: true } },
        { $sort: { createdAt: -1 } },
        { $skip: (pageNum - 1) * pageSize },
        { $limit: pageSize }
    ];

    const tickets = await TicketBooking.aggregate(pipeline);

    // Count total bookings (for pagination)
    const totalTickets = await TicketBooking.countDocuments({ $and: [matchBooking, { $or: orGeneratedBy }] });
    const totalPages = Math.ceil(totalTickets / pageSize);

    return successRes(res, 200, true, "Tickets fetched successfully", {
        totalTickets,
        totalPages,
        currentPage: pageNum,
        pageSize,
        tickets
    });
});


const getTicketsBySessionId = catchAsync(async (req, res, next) => {
    let { sessionId, page = 1, limit = 10, ticketStatus } = req.query;

    if (!isValidId(sessionId)) return next(new AppError('Invalid session id', 400));

    if (ticketStatus && !['pending', 'confirmed', 'failed'].includes(ticketStatus)) {
        return next(new AppError('Invalid status value', 400));
    }

    if (!ticketStatus) ticketStatus = "confirmed";

    // Count total tickets
    const countBuilder = new QueryBuilder(TicketBooking);
    const totalTickets = await countBuilder
        .filter({
            eventSession: new mongoose.Types.ObjectId(sessionId),
            ticketStatus,
            $or: [
                { generatedBy: "user" },
                { generatedBy: { $exists: false } } // agar field hi nahi hai
            ]
        })
        .count();

    // Fetch paginated tickets
    let qb = new QueryBuilder(TicketBooking);
    const tickets = await qb.aggregate([
        {
            $match: {
                eventSession: new mongoose.Types.ObjectId(sessionId),
                ticketStatus,
                $or: [
                    { generatedBy: "user" },
                    { generatedBy: { $exists: false } }
                ]
            },
        },
        {
            $lookup: {
                from: "eventsessions",
                localField: "eventSession",
                foreignField: "_id",
                as: "eventSessionDetails",
            },
        },
        { $unwind: "$eventSessionDetails" },
        {
            $lookup: {
                from: "events",
                localField: "eventSessionDetails.event",
                foreignField: "_id",
                as: "eventDetails",
            },
        },
        {
            $lookup: {
                from: "users",
                localField: "user",
                foreignField: "_id",
                as: "userDetails",
            },
        },
        { $unwind: "$userDetails" },
        { $sort: { createdAt: -1 } },
        { $skip: (parseInt(page, 10) - 1) * parseInt(limit, 10) },
        { $limit: parseInt(limit, 10) },
    ]).exec();

    return successRes(res, 200, true, "Tickets fetched successfully", {
        total: totalTickets,
        page: parseInt(page, 10),
        limit: parseInt(limit, 10),
        data: tickets
    });
});


const getTicketById = catchAsync(async (req, res, next) => {
    const ticketId = req.query.ticketId;

    if (!isValidId(ticketId)) {
        return next(new AppError('Invalid ticket id', 400));
    }

    const qb = new QueryBuilder(TicketBooking);
    const ticket = await qb
        .filter({ _id: new mongoose.Types.ObjectId(ticketId) })
        .populate("user", "-password") // Adjust fields as needed
        .exec();

    if (!ticket) {
        return next(new AppError('Ticket not found', 404));
    }

    return successRes(res, 200, true, "Ticket fetched successfully", ticket);
});


