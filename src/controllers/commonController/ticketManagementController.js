const generateTicketFromAdminSide = catchAsync(async (req, res, next) => {
    let {
        sessionId,
        eventId,
        quantity,
        isVipTicket = false,
        isValidForAllDays = false,
        ticketName
    } = req.body;

    // 🔹 Validate IDs
    if (!isValidId(sessionId)) return next(new AppError("Invalid session id", 400));
    if (!isValidId(eventId)) return next(new AppError("Invalid event id", 400));

    // 🔹 Validate quantity
    if (!quantity) return next(new AppError("Quantity is required", 400));
    quantity = parseInt(quantity, 10);
    if (isNaN(quantity) || quantity <= 0) {
        return next(new AppError("Quantity must be a positive integer", 400));
    }

    // 🔹 Limit per booking (Admin override allowed via env)
    const limitPerBooking = parseInt(process.env.MAX_TICKETS_PER_BOOKING || 20, 10);
    if (quantity > limitPerBooking) {
        return next(new AppError(`You can book a maximum of ${limitPerBooking} tickets at a time`, 400));
    }

    // 🔹 Validate session
    const sessionData = await EventSession.findOne({
        _id: sessionId,
        event: eventId,
        isDeleted: false
    });
    if (!sessionData) return next(new AppError("Event session not found", 404));

    // 🔹 Validate event
    const eventData = await Event.findOne({ _id: eventId, isDeleted: false });
    if (!eventData) return next(new AppError("Event not found", 404));

    //Expiry Check
    const today = new Date();
    today.setHours(0, 0, 0, 0); // reset time to midnight

    const sessionDate = new Date(sessionData.date);
    sessionDate.setHours(0, 0, 0, 0);
    console.log(sessionDate, "sessionDate", today, "today")
    if (sessionDate < today) {
        return next(new AppError("This event session has already expired", 400));
    }


    // 🔹 Price calculation
    const pricePerTicket = sessionData.pricePerTicket || eventData.price || 0;
    const totalAmount = pricePerTicket * quantity;

    // 🔹 Final flag for validity
    const finalIsValidForAllDays = isVipTicket ? true : !!isValidForAllDays;
    console.log("finalIsValidForAllDays", finalIsValidForAllDays)
    // 🔹 Attendee details (condition based)
    const attendeeName = isVipTicket
        ? `${ticketName}`
        : isValidForAllDays
            ? `${ticketName}`
            : `${ticketName}`;

    const attendeeDetails = Array.from({ length: 1 }, (_, i) => ({
        name: `${attendeeName}`,
        phone: ""
    }));

    // 🔹 Capacity check (only for normal non-allDay tickets)
    if (!isVipTicket && !finalIsValidForAllDays) {
        if (sessionData.remainingCapacity < quantity) {
            return next(new AppError("Not enough tickets available", 400));
        }
    }

    // 🔹 Create booking (without payment)
    const booking = await TicketBooking.create({
        user: req.user._id, // Admin ID
        eventSession: sessionId,
        event: eventId,
        quantity,
        attendeeDetails,
        pricePerTicket,
        totalAmount,
        currency: "INR",
        paymentMethod: "razorpay", // keeping enum value same
        paymentStatus: "paid",     // mark as paid since admin generated
        ticketStatus: "pending",   // can later be confirmed
        tickets: [],
        notes: "Admin generated booking",
        generatedBy: "admin",
        isVipTicket,
        validForAllDays: finalIsValidForAllDays
    });

    // 🔹 Update session capacity only if applicable
    if (!isVipTicket && !finalIsValidForAllDays) {
        sessionData.remainingCapacity -= quantity;
        await sessionData.save();
    }

    return successRes(
        res,
        201,
        true,
        "Tickets generated by admin successfully",
        { bookingId: booking._id }
    );
});

